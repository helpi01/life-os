// --- 3. Объяснение логики плана (для UI «Почему ИИ предлагает это») ---
export function whyThisPlan(goal: string, plan: Plan): string {
  const type = detectGoalType(goal)
  const firstWeek = plan.weeks[0]?.week || ''
  const firstTasks = plan.weeks[0]?.tasks?.slice(0, 3).map(t => t.name).join(', ') || 'базовые действия'

  const typeDesc: Record<string, string> = {
    finance: 'финансовой цели',
    weight: 'работы с весом и питанием',
    study: 'обучения и подготовки к экзамену',
    sport: 'спортивной подготовки',
    project: 'запуска проекта',
    habit_quit: 'отказа от вредной привычки',
    other: 'достижения цели'
  }

  const desc = typeDesc[type] || typeDesc.other

  return `План для ${desc} построен поэтапно: ${firstWeek.toLowerCase()} начинается с ${firstTasks.toLowerCase()}. Первые недели закладывают фундамент (привычки, учёт, базовые навыки), далее — наращивание объёма и сложности, последние — закрепление результата и перевод в систему.`
}