// --- Вспомогательная: определение типа цели по ключевым словам ---
function detectGoalType(goal: string): 'finance' | 'weight' | 'study' | 'sport' | 'project' | 'habit_quit' | 'other' {
  const g = goal.toLowerCase()
  if (/накопить|сэкономить|отложить|бюджет|финанс|денег|рубл|заработ|заработ|прибыл|инвест|купон|дивиденд|акци|облигац|фонд/.test(g)) return 'finance'
  if (/похуд|вес|кг|форму|сбросить|жир|калори|питан|диет|еда|объем|талия|брюх/.test(g)) return 'weight'
  if (/экзамен|учить|курс|учиться|выучить|изучить|запомнить|пробел|предмет|тема|лекц|семинар|домашка|дедлайн|сесси/.test(g)) return 'study'
  if (/бег|марафон|тренир|спорт|зал|фитнес|крест|планк|присед|жим|тяг|интервал|темп|длинн|спринт|км|мил/.test(g)) return 'sport'
  if (/запустить|проект|сайт|приложение|мвп|деплой|релиз|прототип|тз|техзад|архитектур|дизайн|макет|фича|фичи|бэкенд|фронтенд|апи|база|микросервис/.test(g)) return 'project'
  if (/бросить|курить|алкогол|привыч|вредн|зависимост|наушник|телефон|соцсет|дофамин|экран|экранн/.test(g)) return 'habit_quit'
  return 'other'
}

// --- 1. Генерация плана через ИИ (с fallback) ---
export async function generatePlan(goal: string): Promise<Plan> {
  try {
    const settings = getAiSettings('text')
    const prompts = loadPrompts()
    const promptDef = PROMPTS.find(p => p.id === 'plan')
    const sys = prompts.plan || (promptDef ? promptDef.text : '')

    const res = await chatJson<{ weeks: { week: string; tasks: { name: string }[] }[] }>(
      settings,
      sys,
      'Цель: ' + goal + '.\nСрок: 6 недель.\nСоставь план из 6 недель по 4-6 конкретных маленьких задач в каждой. Верни ТОЛЬКО JSON.'
    )

    if (res && Array.isArray(res.weeks) && res.weeks.length) {
      // Нормализуем: оставляем первые 6 недель, по максимум 6 задач
      const weeks = res.weeks.slice(0, 6).map((w, i) => ({
        week: w.week || `Неделя ${i + 1}`,
        tasks: (w.tasks || []).slice(0, 6).map(t => typeof t === 'string' ? { name: t } : { name: t?.name || '' }).filter(t => t.name)
      }))
      return { weeks }
    }
    throw new Error('Пустой или некорректный ответ ИИ')
  } catch (e) {
    // Любая ошибка (нет ключа, сеть, парсинг) — тихий fallback
    return fallbackPlan(goal)
  }
}

